_SUFFIXES = ('ترین', 'تر', 'ای', 'ه', 'ی')


def _sentiment_of(word: str) -> str | None:
    """
    Return 'positive', 'negative', or None.
    Tries exact match first, then strips common inflectional suffixes.
    """
    if word in POSITIVE_WORDS:
        return 'positive'
    if word in NEGATIVE_WORDS:
        return 'negative'
    for suffix in _SUFFIXES:
        if len(word) > len(suffix) + 2:
            stem = word[:-len(suffix)]
            if stem in POSITIVE_WORDS:
                return 'positive'
            if stem in NEGATIVE_WORDS:
                return 'negative'
    return None


# ──────────────────────────────────────────────────────────────────────────────
# Scorer
# ──────────────────────────────────────────────────────────────────────────────

_NEUTRAL_BAND = 0.08   # a 55/45 split → definite label


class PersianLexiconScorer:
    """
    Scores Persian text sentiment using the lexicon above.

    Algorithm
    ---------
    1. Build a set of indices where negation words appear.
    2. For each non-negation token, check if an intensifier/diminisher
       appears in the ±1 neighbouring position.
    3. Check if a negation word appears within ±2 positions (bidirectional).
    4. Accumulate weighted pos/neg counts; flip polarity when negated.
    5. Derive sentiment from the ratio, with a narrow neutral band.
    """

    def score(self, text: str) -> dict:
        words = text.split()
        n = len(words)

        neg_positions = frozenset(
            i for i, w in enumerate(words) if w in _NEGATION_WORDS
        )

        pos = neg = 0.0

        for i, word in enumerate(words):
            if word in _NEGATION_WORDS:
                continue
            if word in _INTENSIFIERS or word in _DIMINISHERS:
                continue

            sentiment = _sentiment_of(word)
            if sentiment is None:
                continue

            # ── modifier: check ±1 neighbours ─────────────────────────────
            mult = 1.0
            for delta in (-1, 1):
                j = i + delta
                if 0 <= j < n:
                    if words[j] in _INTENSIFIERS:
                        mult = max(mult, _INTENSIFIERS[words[j]])
                    elif words[j] in _DIMINISHERS:
                        mult = min(mult, _DIMINISHERS[words[j]])

            # ── negation: check ±2 positions (bidirectional) ───────────────
            is_negated = any(abs(i - j) <= 2 for j in neg_positions)

            if sentiment == 'positive':
                if is_negated:
                    neg += mult
                else:
                    pos += mult
            else:
                if is_negated:
                    pos += mult
                else:
                    neg += mult

        total = pos + neg
        if total == 0.0:
            return {
                'sentiment': 'neutral',
                'confidence': 0.5,
                'scores': {'positive': 0.33, 'negative': 0.33, 'neutral': 0.34},
            }

        pos_ratio = pos / total
        neg_ratio = neg / total
        balance = abs(pos_ratio - neg_ratio)

        if balance <= _NEUTRAL_BAND:
            sentiment = 'neutral'
            confidence = round(0.5 + balance, 4)
            neutral_score = round(1.0 - balance, 4)
        elif pos_ratio > neg_ratio:
            sentiment = 'positive'
            confidence = round(pos_ratio, 4)
            neutral_score = round(max(0.0, 1.0 - pos_ratio), 4)
        else:
            sentiment = 'negative'
            confidence = round(neg_ratio, 4)
            neutral_score = round(max(0.0, 1.0 - neg_ratio), 4)

        return {
            'sentiment': sentiment,
            'confidence': confidence,
            'scores': {
                'positive': round(pos_ratio, 4),
                'negative': round(neg_ratio, 4),
                'neutral': neutral_score,
            },
        }
